def timeline_entries() -> list[dict]:
    """Return independent chronological records, with visual track metadata.

    Tracks organize a selected reading history; they do not imply that the
    disciplines or ideas developed independently. Opening a source is explicit.
    """
    entries = deepcopy(_ENTRIES + _LITERATURE)
    for entry in entries:
        if "track" not in entry:
            entry["track"] = next((track for track, identities in _EXISTING_TRACKS.items()
                                   if entry["id"] in identities), "Deep learning")
        entry.setdefault("short_title", _SHORT_TITLES.get(entry["id"], entry["title"]))
    return sorted(entries, key=lambda entry: entry["year"])


